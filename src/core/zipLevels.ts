/** Joins a level's chunks into rows of characters ('.' becomes a space). */
export function levelRows(def: LevelDef): string[] {
  const rows = Array.from({ length: 12 }, () => '');
  for (const name of def.chunks) {
    const c = CHUNKS[name];
    if (!c || c.length !== 12) throw new Error(`bad chunk ${name}`);
    const w = c[0].length;
    c.forEach((r, i) => { if (r.length !== w) throw new Error(`ragged chunk ${name} row ${i}`); rows[i] += r; });
  }
  return rows.map(r => r.replace(/\./g, ' '));
}
